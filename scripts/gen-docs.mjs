#!/usr/bin/env node
/**
 * Generate VitePress reference pages from lock files:
 *   shared/frame-props.json              → folded into website/src/generated/objects.md (Frames)
 *   shared/diagnostics.json              → website/src/generated/diagnostics.md
 *   shared/keywords.json                 → appended to website/src/generated/diagnostics.md
 *   shared/language-objects.json         → website/src/generated/objects.md
 *   shared/schema/*.json                 → website/src/generated/json-ir.md
 *   grammar/pdl.ebnf                     → website/src/generated/grammar.md (unpublished wrap)
 *   test-fixtures/pdl/errors/** + tests/ → website/src/generated/error-fixtures.md
 *
 * Edit grammar/pdl.ebnf by hand. This script does not overwrite it.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "website", "src", "generated");
const REPO_BLOB = "https://github.com/VeryTinyMachines/pdl/blob/main";

const GENERATED_BANNER = `<!-- Generated by scripts/gen-docs.mjs — do not edit. -->\n`;

function loadJson(rel) {
  return JSON.parse(readFileSync(join(ROOT, rel), "utf8"));
}

function escapeCell(s) {
  return String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function objectSlug(name) {
  return String(name).toLowerCase().replace(/[^a-z0-9]+/g, "");
}

function frameSlug(ctor) {
  return ctor === "Icon" || ctor === "Media" ? `${objectSlug(ctor)}-frame` : objectSlug(ctor);
}

function buildObjectCatalog(objects) {
  const types = new Map();
  const frames = new Map();
  const frameCtors = new Map();
  const ctors = new Map();
  const typeCase = new Map();
  const caseOwners = new Map();
  const ci = new Map();

  const addType = (name, slug) => {
    if (!name || types.has(name)) return;
    types.set(name, slug);
    const lower = name.toLowerCase();
    if (!ci.has(lower)) ci.set(lower, []);
    ci.get(lower).push(slug);
  };
  const addCases = (typeName, slug, cases) => {
    for (const raw of cases ?? []) {
      const cse = typeof raw === "string" ? raw : raw.case;
      if (!cse) continue;
      typeCase.set(`${typeName.toLowerCase()}.${cse}`, slug);
      if (!caseOwners.has(cse)) caseOwners.set(cse, new Set());
      caseOwners.get(cse).add(slug);
    }
  };

  for (const t of objects.tokenTypes ?? []) addType(t.name, objectSlug(t.name));
  for (const e of objects.enums ?? []) {
    addType(e.name, objectSlug(e.name));
    addCases(e.name, objectSlug(e.name), e.cases);
  }
  for (const e of objects.preludeEnums ?? []) {
    addType(e.name, objectSlug(e.name));
    addCases(e.name, objectSlug(e.name), e.cases);
  }
  for (const t of objects.paramScalars ?? []) addType(t.name, objectSlug(t.name));
  for (const p of objects.hostProtocols ?? []) addType(p.name, objectSlug(p.name));
  addType("theme", "theme");
  addType("Theme", "theme");
  addType("typeStyle", "typestyle");
  addType("let", "let");
  addType("Let", "let");
  addType("parameters", "parameters");
  addType("if", "conditionals");
  addType("else", "conditionals");
  addType("null", "null");
  addType("self", "self");
  addType("ForEach", "foreach");
  addType("import", "files");
  addType("fixtures", "fixtures");
  addType("usage", "usage");
  addType("Usage", "usage");
  addType("extend", "extend");
  addType("Extend", "extend");
  addType("Rule", "rule");
  addType("rules", "rule");

  for (const k of objects.frameKinds ?? []) {
    const slug = frameSlug(k.ctor);
    frameCtors.set(k.ctor, slug);
    frames.set(k.name, slug);
    if (!types.has(k.ctor)) frames.set(k.ctor, slug);
  }

  for (const c of objects.constructors ?? []) {
    if (c.kind === "frame") continue;
    if (types.has(c.name)) ctors.set(c.name, types.get(c.name));
    else ctors.set(c.name, objectSlug(c.name));
  }

  frames.set("children", "children");
  ctors.set("typeStyle", "typestyle");
  ctors.set("ForEach", "foreach");
  ctors.set("import", "files");
  ctors.set("variant", "variants");
  ctors.set("enum", "variants");
  ctors.set("usage", "usage");
  ctors.set("extend", "extend");
  ctors.set("Rule", "rule");
  ctors.set("rules", "rule");
  ctors.set("Spacer", "spacer");
  ctors.set("Corner", "corner");
  ctors.set("MediaLayer", "medialayer");
  ctors.set("IconRef", "iconref");

  const uniqueCases = new Map();
  for (const [cse, owners] of caseOwners) {
    if (owners.size === 1) uniqueCases.set(cse, [...owners][0]);
  }

  return { types, frames, frameCtors, ctors, typeCase, uniqueCases, ci };
}

function lookupName(name, catalog) {
  if (!name || !catalog) return null;
  if (catalog.frames.has(name)) return catalog.frames.get(name);
  if (catalog.types.has(name)) return catalog.types.get(name);
  if (catalog.ctors.has(name)) return catalog.ctors.get(name);
  const hits = catalog.ci.get(name.toLowerCase());
  if (hits?.length === 1) return hits[0];
  return null;
}

function ctorSlug(name, catalog) {
  return catalog.frameCtors.get(name) ?? catalog.ctors.get(name) ?? catalog.types.get(name) ?? null;
}

function mdObj(label, slug) {
  return `[\`${label}\`](#${slug})`;
}

function linkCodeInner(inner, catalog, self) {
  const dotted = inner.match(/^([A-Za-z][A-Za-z0-9]*)\.([A-Za-z][A-Za-z0-9]*)$/);
  if (dotted) {
    const slug = catalog.typeCase.get(`${dotted[1].toLowerCase()}.${dotted[2]}`) ?? lookupName(dotted[1], catalog);
    if (slug && slug !== self) return mdObj(inner, slug);
  }
  const call = inner.match(/^([A-Za-z][A-Za-z0-9]*)\(\s*(?:…|\.\.\.)?\s*\)$/);
  if (call) {
    const slug = ctorSlug(call[1], catalog);
    if (slug && slug !== self) return mdObj(inner, slug);
  }
  const cse = inner.match(/^\.([A-Za-z][A-Za-z0-9]*)$/);
  if (cse) {
    const slug = catalog.uniqueCases.get(cse[1]);
    if (slug && slug !== self) return mdObj(inner, slug);
  }
  const bare = inner.replace(/\(\s*…\s*\)$/, "");
  const slug = lookupName(bare, catalog);
  if (slug && slug !== self) return mdObj(inner, slug);
  return `\`${inner}\``;
}

function linkProse(text, catalog, self = null) {
  if (!text || !catalog) return text ?? "";
  const holes = [];
  let s = String(text).replace(/\[([^\]]+)\]\([^)]+\)/g, (m) => {
    holes.push(m);
    return `\0${holes.length - 1}\0`;
  });

  s = s.replace(/`([^`]+)`/g, (_, inner) => {
    const linked = linkCodeInner(inner, catalog, self);
    holes.push(linked);
    return `\0${holes.length - 1}\0`;
  });

  s = s.replace(/\b([A-Za-z][A-Za-z0-9]*)\.([A-Za-z][A-Za-z0-9]*)\b/g, (m, type, cse) => {
    const slug = catalog.typeCase.get(`${type.toLowerCase()}.${cse}`) ?? lookupName(type, catalog);
    if (!slug || slug === self) return m;
    const linked = mdObj(m, slug);
    holes.push(linked);
    return `\0${holes.length - 1}\0`;
  });

  s = s.replace(/(?<![`\w])\.([A-Za-z][A-Za-z0-9]*)\b/g, (m, cse) => {
    const slug = catalog.uniqueCases.get(cse);
    if (!slug || slug === self) return m;
    const linked = mdObj(m, slug);
    holes.push(linked);
    return `\0${holes.length - 1}\0`;
  });

  const names = [
    ...catalog.types.keys(),
    ...catalog.frames.keys(),
    ...catalog.ctors.keys(),
  ].filter((n, i, arr) => arr.indexOf(n) === i && /[A-Z]/.test(n)).sort((a, b) => b.length - a.length);
  if (names.length) {
    const re = new RegExp(`(?<!\\[)\\b(${names.map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})\\b(?!\\s*\\()`, "g");
    s = s.replace(re, (m) => {
      const slug = lookupName(m, catalog);
      if (!slug || slug === self) return m;
      const linked = mdObj(m, slug);
      holes.push(linked);
      return `\0${holes.length - 1}\0`;
    });
  }

  return s.replace(/\0(\d+)\0/g, (_, i) => holes[Number(i)]);
}

function linkUsedOn(items, catalog) {
  return (items ?? [])
    .map((u) =>
      String(u)
        .split(".")
        .map((seg) => {
          const slug = lookupName(seg, catalog);
          return slug ? mdObj(seg, slug) : `\`${seg}\``;
        })
        .join("."),
    )
    .join(", ");
}

function formatType(name, typeKey, kind, catalog) {
  if (name === "content") return mdObj("String", "string");
  if (name === "fontFamily") return mdObj("FontFamily", "fontfamily");
  if (name === "style") return mdObj("typeStyle", "typestyle");
  if (kind?.typeName) {
    const slug = lookupName(kind.typeName, catalog);
    return slug ? mdObj(kind.typeName, slug) : `\`${kind.typeName}\``;
  }
  if (Array.isArray(kind?.tokenTypes) && kind.tokenTypes.length) {
    return kind.tokenTypes
      .map((t) => {
        const slug = lookupName(t, catalog);
        return slug ? mdObj(t, slug) : `\`${t}\``;
      })
      .join(", ");
  }
  if (typeKey === "styleRef") return mdObj("typeStyle", "typestyle");
  if (typeKey === "booleanOrCondition") return "`Bool` or condition";
  if (typeKey === "structural") return "`structural`";
  return `\`${escapeCell(typeKey)}\``;
}

function formatValues(kind, catalog) {
  if (!kind) return "—";
  const bits = [];
  if (Array.isArray(kind.cases) && kind.cases.length) {
    const slug = kind.typeName ? lookupName(kind.typeName, catalog) : null;
    bits.push(
      kind.cases.map((c) => (slug ? mdObj(`.${c}`, slug) : `\`.${c}\``)).join(" · "),
    );
  }
  if (kind.range) bits.push(`${kind.range[0]}…${kind.range[1]}`);
  if (kind.nonNegativeNumber) bits.push("≥ 0");
  if (kind.positiveNumber) bits.push("> 0");
  if (kind.tokenTypes?.includes("Sizing") && !kind.cases?.length) {
    bits.push(`${mdObj(".hug", "sizing")} · ${mdObj(".fill", "sizing")} · \`.fixed(n)\``);
  }
  if (!bits.length && Array.isArray(kind.accept)) {
    bits.push(kind.accept.filter((a) => a !== "dotEnum" && a !== "ident" && a !== "call").join(", ") || "—");
  }
  return bits.join(" · ") || "—";
}

function kindProps(kindName, kinds, special) {
  const props = { ...(kinds[kindName]?.props ?? {}) };
  for (const [name, spec] of Object.entries(special ?? {})) {
    if (name === "children") continue;
    if (!spec.kinds?.includes(kindName)) continue;
    if (spec.type) props[name] = { type: spec.type };
    else if (spec.structural) props[name] = { type: "structural" };
  }
  return props;
}

function propRows(props, valueKinds, catalog) {
  const names = Object.keys(props).sort((a, b) => a.localeCompare(b));
  const lines = [
    "| Property | Type | Values |",
    "|----------|------|--------|",
  ];
  for (const name of names) {
    const typeKey = props[name].type;
    const kind = valueKinds[typeKey];
    lines.push(
      `| \`${name}\` | ${formatType(name, typeKey, kind, catalog)} | ${formatValues(kind, catalog)} |`,
    );
  }
  return lines.join("\n");
}

function diagRow(d) {
  const name = d.retired ? "*(retired)*" : `\`${d.name}\``;
  const trigger = escapeCell(d.trigger);
  return `| **${d.code}** | ${name} | ${trigger} |`;
}

function renderDiagnostics(sot, keywords) {
  let body = `${GENERATED_BANNER}
# Diagnostics

When compilation stops, the message includes a **PDL-E** code (error) or **PDL-W** code (warning). Look up the code here. Codes are never reused after retirement.

Catalog: [\`shared/diagnostics.json\`](${REPO_BLOB}/shared/diagnostics.json) (language **${sot.languageVersion}**).

## Errors (PDL-E0xx)

| Code | Name | Trigger |
|------|------|---------|
`;
  for (const d of sot.errors) body += `${diagRow(d)}\n`;

  body += `
## Warnings (PDL-W0xx)

| Code | Name | Trigger |
|------|------|---------|
`;
  for (const d of sot.warnings) body += `${diagRow(d)}\n`;

  body += `
## Message requirements

Every diagnostic **MUST** include:

1. The error or warning code (e.g. \`PDL-E007\`).
2. The source file path and line number (and column where determinable).
3. A human-readable message describing what was found and what was expected.
4. For errors referencing another location (e.g. \`PDL-E003\` duplicate), the location of the first occurrence.
`;
  return body + renderKeywords(keywords);
}

function renderKeywords(sot) {
  let body = `
## Keywords

Words you cannot use as your own names (**PDL-E018**). You do not need to memorize this while learning; the compiler will say so.

Catalog: [\`shared/keywords.json\`](${REPO_BLOB}/shared/keywords.json) (language **${sot.languageVersion}**).

`;
  for (const group of sot.groups) {
    body += `### ${group.title}\n\n`;
    if (group.note) body += `${group.note}\n\n`;
    body += "| Word | Note |\n|------|------|\n";
    for (const w of group.words) {
      body += `| \`${w.word}\` | ${escapeCell(w.note ?? "—")} |\n`;
    }
    body += "\n";
  }
  return body;
}

function schemaFieldTable(schema) {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines = [
    "| Field | Required | Notes |",
    "|-------|----------|-------|",
  ];
  for (const [name, spec] of Object.entries(props)) {
    const req = required.has(name) ? "yes" : "no";
    const bits = [];
    if (spec.const !== undefined) bits.push(`const \`${JSON.stringify(spec.const).replace(/"/g, "")}\``);
    if (spec.type) bits.push(Array.isArray(spec.type) ? spec.type.join(" \\| ") : spec.type);
    if (spec.description) bits.push(spec.description);
    if (spec.additionalProperties) bits.push("map");
    lines.push(`| \`${name}\` | ${req} | ${bits.join(" · ") || "—"} |`);
  }
  return lines.join("\n");
}

