function assertExampleCoverage(objects) {
  const missing = [];
  for (const e of objects.enums ?? []) {
    if (!e.example) missing.push(`enum ${e.name}`);
  }
  for (const e of objects.preludeEnums ?? []) {
    if (!e.example) missing.push(`prelude enum ${e.name}`);
  }
  for (const p of objects.hostProtocols ?? []) {
    if (!p.example) missing.push(`host protocol ${p.name}`);
  }
  for (const k of objects.frameKinds ?? []) {
    if (!k.example) missing.push(`frame ${k.name}`);
  }
  const spacer = (objects.constructors ?? []).find((c) => c.name === "Spacer");
  if (!spacer?.example) missing.push("Spacer example");
  for (const key of [
    "declarationExample",
    "constructorsExample",
    "childrenExample",
    "eventDirectionsExample",
    "emitExample",
    "protocolExample",
    "forEachExample",
    "sampleExample",
  ]) {
    if (!objects[key]) missing.push(key);
  }
  if (!objects.ruleQuery?.example) missing.push("ruleQuery.example");
  if (!objects.rule?.examples?.length) missing.push("rule.examples");
  for (const [i, ex] of (objects.rule?.examples ?? []).entries()) {
    if (!ex.title || !ex.code) missing.push(`rule.examples[${i}]`);
  }
  if (!objects.fixtures?.complexExample) missing.push("fixtures.complexExample");
  for (const key of [
    "theme",
    "lets",
    "parameters",
    "conditionals",
    "typeStyle",
    "null",
    "conditions",
    "syntax",
    "files",
    "arrayChildren",
    "variants",
    "self",
    "motion",
    "fixtures",
    "usage",
    "extend",
    "rule",
  ]) {
    const obj = objects[key];
    if (!obj?.example) missing.push(`${key}.example`);
    if (!Array.isArray(obj?.accept) || !obj.accept.length) missing.push(`${key}.accept`);
  }
  if (missing.length) {
    throw new Error(
      `shared/language-objects.json is missing examples:\n  - ${missing.join("\n  - ")}`,
    );
  }
}

