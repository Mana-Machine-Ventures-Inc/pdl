#!/usr/bin/env node
/**
 * Generate docs/reference/symbols/* and docs/reference/language/errors.md
 * from shared/language-model.json + shared/frame-props.json.
 *
 *   node scripts/generate-language-docs.mjs
 *   node scripts/generate-language-docs.mjs --check   # exit 1 if stale
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MODEL_PATH = join(ROOT, "shared/language-model.json");
const FRAME_PROPS_PATH = join(ROOT, "shared/frame-props.json");
const OUT_SYMBOLS = join(ROOT, "docs/reference/symbols");
const OUT_SYMBOLS_INDEX = join(ROOT, "docs/reference/symbols.md");
const OUT_ERRORS = join(ROOT, "docs/reference/language/errors.md");
const CHECK = process.argv.includes("--check");

const GENERATED_BANNER =
  "<!-- Generated by scripts/generate-language-docs.mjs — do not edit by hand. -->\n" +
  "<!-- Sources: shared/language-model.json, shared/frame-props.json -->\n\n";

const KIND_FOLDER = {
  enum: "enums",
  type: "types",
  frame: "frames",
  ctor: "constructors",
  protocol: "protocols",
};

function loadJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function slug(name) {
  return String(name)
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

function ensureDir(dir) {
  mkdirSync(dir, { recursive: true });
}

/**
 * @param {string} name
 * @param {keyof typeof KIND_FOLDER} kind
 * @param {"index" | "nested"} from - index = docs/reference/symbols.md; nested = page under symbols/<folder>/
 * @param {string} [label]
 */
function linkSymbol(name, kind, from = "nested", label = name) {
  const folder = KIND_FOLDER[kind];
  const file = `${slug(name)}.md`;
  const href =
    from === "index"
      ? `symbols/${folder}/${file}`
      : `../${folder}/${file}`;
  return `[${label}](${href})`;
}

/** Link from a nested symbol page back to the canonical index. */
function indexLink(anchor, label) {
  return `[${label}](../../symbols.md${anchor ? "#" + anchor : ""})`;
}

/** Collect host enums from frame-props valueKinds (typeName + cases). */
function enumsFromFrameProps(frameProps) {
  const byName = new Map();
  for (const [vkName, vk] of Object.entries(frameProps.valueKinds || {})) {
    if (!vk.typeName || !Array.isArray(vk.cases)) continue;
    const existing = byName.get(vk.typeName);
    if (!existing) {
      byName.set(vk.typeName, {
        name: vk.typeName,
        cases: [...vk.cases],
        valueKinds: [vkName],
        source: "frame-props",
        summary: `Host enum used by frame properties (\`${vkName}\`).`,
      });
    } else {
      existing.valueKinds.push(vkName);
      for (const c of vk.cases) {
        if (!existing.cases.includes(c)) existing.cases.push(c);
      }
    }
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function valueKindLabel(frameProps, typeKey) {
  const vk = frameProps.valueKinds?.[typeKey];
  if (!vk) return typeKey;
  if (vk.typeName) {
    const cases = (vk.cases || []).map((c) => `\`.${c}\``).join(", ");
    return cases ? `${vk.typeName} — ${cases}` : vk.typeName;
  }
  if (typeKey === "sizing") {
    return "Sizing — `.hug`, `.fill`, `.fixed(n)`, `.flex(…)`, `.aspect(…)` (number → `.fixed`)";
  }
  if (typeKey === "edgeInsets") {
    return "EdgeInsets — `EdgeInsets(…)` or uniform number sugar";
  }
  if (typeKey === "colorOrLayers") {
    return "Color | layer stack | Background | Foreground";
  }
  if (vk.tokenTypes?.length) return vk.tokenTypes.join(" | ");
  return (vk.accept || []).join(" | ") || typeKey;
}

function writeOrCheck(path, body) {
  const next = GENERATED_BANNER + body;
  if (CHECK) {
    if (!existsSync(path)) {
      console.error(`missing generated file: ${relative(ROOT, path)}`);
      process.exitCode = 1;
      return;
    }
    const prev = readFileSync(path, "utf8");
    if (prev !== next) {
      console.error(`stale generated file: ${relative(ROOT, path)}`);
      process.exitCode = 1;
    }
    return;
  }
  ensureDir(dirname(path));
  writeFileSync(path, next, "utf8");
}

function collectWrittenFiles(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, ent.name);
    if (ent.isDirectory()) collectWrittenFiles(p, acc);
    else acc.push(p);
  }
  return acc;
}

function hashFiles(paths) {
  const h = createHash("sha256");
  for (const p of paths.sort()) {
    h.update(relative(ROOT, p));
    h.update("\0");
    h.update(readFileSync(p));
    h.update("\0");
  }
  return h.digest("hex").slice(0, 16);
}

function main() {
  const model = loadJson(MODEL_PATH);
  const frameProps = loadJson(FRAME_PROPS_PATH);

  if (!CHECK) {
    rmSync(OUT_SYMBOLS, { recursive: true, force: true });
    ensureDir(OUT_SYMBOLS);
    ensureDir(join(OUT_SYMBOLS, "frames"));
    ensureDir(join(OUT_SYMBOLS, "enums"));
    ensureDir(join(OUT_SYMBOLS, "types"));
    ensureDir(join(OUT_SYMBOLS, "constructors"));
    ensureDir(join(OUT_SYMBOLS, "protocols"));
  }

  const hostEnums = enumsFromFrameProps(frameProps);
  const hostEnumNames = new Set(hostEnums.map((e) => e.name));
  const supplementalEnums = (model.enums || []).filter((e) => !hostEnumNames.has(e.name));
  const allEnums = [
    ...hostEnums.map((e) => ({
      ...e,
      notes: undefined,
    })),
    ...supplementalEnums,
  ].sort((a, b) => a.name.localeCompare(b.name));

  // Merge BlurStyle etc. summaries when host enum also listed in model (shouldn't overlap except BlurStyle)
  for (const e of model.enums || []) {
    if (hostEnumNames.has(e.name)) {
      const target = allEnums.find((x) => x.name === e.name);
      if (target) {
        target.summary = e.summary || target.summary;
        target.notes = e.notes;
        if (e.cases?.length) target.cases = e.cases;
      }
    }
  }

  const tokenByName = new Map((model.tokenTypes || []).map((t) => [t.name, t]));
  const enumByName = new Map(allEnums.map((e) => [e.name, e]));
  const frameByName = new Map((model.frameKinds || []).map((f) => [f.name, f]));
  const ctorByName = new Map((model.constructors || []).map((c) => [c.name, c]));

  // —— Frame pages ——
  for (const fk of model.frameKinds || []) {
    const kindProps = frameProps.kinds?.[fk.name]?.props || {};
    const rows = Object.entries(kindProps).map(
      ([prop, meta]) =>
        `| \`${prop}\` | ${valueKindLabel(frameProps, meta.type)} |`,
    );
    const childRows = Object.entries(frameProps.childFlexProps || {}).map(
      ([prop, meta]) =>
        `| \`${prop}\` | ${valueKindLabel(frameProps, meta.type)} |`,
    );
    const specials = Object.entries(frameProps.special || {})
      .filter(([, s]) => s.kinds?.includes(fk.name) || (!s.kinds && s.structural))
      .map(([name, s]) => {
        if (name === "children") return "`children` (structural)";
        if (s.structural) return `\`${name}\` (structural)`;
        return `\`${name}\` — ${valueKindLabel(frameProps, s.type)}`;
      });

    const body = `# ${fk.ctor} (\`${fk.name}\`)

${fk.summary}

| | |
|--|--|
| **IR kind** | \`${fk.name}\` |
| **Constructor** | \`${fk.ctor}(…)\` |
| **Child-flex props** | Yes (when parent is \`layout\`) |

${fk.notes ? `> ${fk.notes}\n` : ""}
## Properties

| Property | Type |
|----------|------|
${rows.join("\n") || "| *(none)* | |"}

## Child-flex properties

Available when this frame is a child of a \`layout\` (or as root flex against the host viewport):

| Property | Type |
|----------|------|
${childRows.join("\n")}

${specials.length ? `## Special\n\n- ${specials.join("\n- ")}\n` : ""}
## See also

- ${indexLink("frame-kinds", "Frame kinds index")}
- Guide: [Components and frames](../../../guide/components-and-frames.md)
- Normative: [\`docs/full-spec.md\` §5](../../../full-spec.md#5--components-frames-and-properties)
`;
    writeOrCheck(join(OUT_SYMBOLS, "frames", `${slug(fk.name)}.md`), body);
  }

  // —— Enum pages ——
  for (const en of allEnums) {
    const subset = model.propertySubsets?.[en.name];
    const caseLines = (en.cases || []).map((c) => `- \`.${c}\` / \`${en.name}.${c}\``);
    let subsetBlock = "";
    if (subset) {
      subsetBlock =
        "\n## Property subsets\n\nSome frame kinds accept a subset of cases:\n\n" +
        Object.entries(subset)
          .map(([k, cases]) => `- **${k}**: ${cases.map((c) => `\`.${c}\``).join(", ")}`)
          .join("\n") +
        "\n";
    }
    const aliasBlock = en.aliases
      ? "\n## Aliases\n\n" +
        Object.entries(en.aliases)
          .map(([a, b]) => `- \`.${a}\` → \`.${b}\``)
          .join("\n") +
        "\n"
      : "";

    const body = `# ${en.name}

${en.summary || "Built-in closed enum."}

| | |
|--|--|
| **Source** | \`${en.source || "language-model"}\` |
| **Cases** | ${(en.cases || []).length} |

## Cases

${caseLines.join("\n") || "*(none)*"}
${aliasBlock}${subsetBlock}
${en.notes ? `## Notes\n\n${en.notes}\n` : ""}
## See also

- ${indexLink("enums", "Enums index")}
- Normative: [\`docs/full-spec.md\` §6](../../../full-spec.md#6--values-and-expressions)
`;
    writeOrCheck(join(OUT_SYMBOLS, "enums", `${slug(en.name)}.md`), body);
  }

  // —— Token / scalar type pages ——
  for (const t of model.tokenTypes || []) {
    const ctors = (t.constructors || [])
      .map((c) => (ctorByName.has(c) ? linkSymbol(c, "ctor", "nested") : `\`${c}\``))
      .join(", ");
    const see = (t.seeAlso || [])
      .map((n) => {
        if (tokenByName.has(n)) return linkSymbol(n, "type", "nested");
        if (enumByName.has(n)) return linkSymbol(n, "enum", "nested");
        return `\`${n}\``;
      })
      .join(", ");

    const body = `# ${t.name}

${t.summary}

| | |
|--|--|
| **Kind** | Token type |
| **Category** | ${t.category} |
| **Constructors** | ${ctors || "—"} |

## RHS

${t.rhs || "—"}

${t.notes ? `## Notes\n\n${t.notes}\n` : ""}
${see ? `## See also\n\n${see}\n` : ""}
## Links

- ${indexLink("types", "Types index")}
- Guide: [Tokens and themes](../../../guide/tokens-and-themes.md)
- Normative: [\`docs/full-spec.md\` §3](../../../full-spec.md#3--tokens-themes-and-type-styles)
`;
    writeOrCheck(join(OUT_SYMBOLS, "types", `${slug(t.name)}.md`), body);
  }

  for (const t of model.paramScalars || []) {
    const body = `# ${t.name}

${t.summary}

| | |
|--|--|
| **Kind** | Param / value-let scalar |
| **Token type?** | No |

${t.notes ? `## Notes\n\n${t.notes}\n` : ""}
## Links

- ${indexLink("types", "Types index")}
- Normative: [\`docs/full-spec.md\` §23.1](../../../full-spec.md#231-built-in-types)
`;
    writeOrCheck(join(OUT_SYMBOLS, "types", `${slug(t.name)}.md`), body);
  }

  // —— Constructor pages ——
  for (const c of model.constructors || []) {
    const produces =
      c.produces == null
        ? "—"
        : frameByName.has(c.produces)
          ? linkSymbol(
              c.produces,
              "frame",
              "nested",
              frameByName.get(c.produces).ctor,
            )
          : tokenByName.has(c.produces)
            ? linkSymbol(c.produces, "type", "nested")
            : `\`${c.produces}\``;

    const body = `# ${c.name}

${c.summary}

| | |
|--|--|
| **Kind** | ${c.kind} |
| **Produces** | ${produces} |
| **Signature** | \`${c.signature || c.name + "(…)"}\` |

${c.notes ? `## Notes\n\n${c.notes}\n` : ""}
## See also

- ${indexLink("constructors", "Constructors index")}
`;
    writeOrCheck(join(OUT_SYMBOLS, "constructors", `${slug(c.name)}.md`), body);
  }

  // —— Protocol pages ——
  for (const p of model.protocols || []) {
    const body = `# ${p.name}

${p.summary}

| | |
|--|--|
| **Role** | ${p.role} |
| **Prelude** | ${p.prelude ? "yes (always in scope)" : "no"} |
| **Source** | \`${p.sourceFile || "—"}\` |

## Inbound channels

${(p.inbound || []).map((c) => `- \`${c}\``).join("\n") || "*(none)*"}

## Host verbs

${(p.verbs || []).map((v) => `- \`${v}\``).join("\n") || "*(none)*"}

## Injected state

${(p.injectedState || []).map((s) => `- \`${s}\``).join("\n") || "*(none)*"}

## See also

- ${indexLink("protocols", "Protocols index")}
- Guide: [Protocols and emits](../../../guide/protocols-and-emits.md)
- Normative: [\`docs/full-spec.md\` §4a′](../../../full-spec.md#4a--host-protocol-prelude-stubs)
`;
    writeOrCheck(join(OUT_SYMBOLS, "protocols", `${slug(p.name)}.md`), body);
  }

  // —— Relationships page ——
  {
    const lines = (model.relationships || []).map((r) => {
      const to = Array.isArray(r.to) ? r.to.map((t) => `\`${t}\``).join(", ") : `\`${r.to}\``;
      return `| \`${r.from}\` | \`${r.kind}\` | ${to} | ${r.notes || ""} |`;
    });
    const body = `# Relationships

PDL is not a classical OO inheritance graph. Built-ins relate by **constructs**, **same RHS**, **shared child-flex props**, and **host conformance**.

| From | Relation | To | Notes |
|------|----------|----|-------|
${lines.join("\n")}

## Frame kind diagram

\`\`\`text
                    ┌──────────── child-flex props ────────────┐
                    │ alignSelf, grow, shrink, position, inset │
                    └───────────────┬──────────────────────────┘
          ┌─────────┬─────────┬─────┴──────┬─────────┐
          ▼         ▼         ▼            ▼         ▼
       Layout     Text      Icon        Media    (any as
       (.layout)  (.text)   (.icon)     (.media)  layout child)
\`\`\`

## Value ctor → type

\`\`\`text
Corner(…)      → CornerRadii
IconRef(…)     → Icon
MediaLayer(…)  → Media
Shadow(…)      → Shadow
EdgeInsets(…)  → EdgeInsets
Blur(…)        → Blur
Vibrancy(…)    → Vibrancy
Ramp(…)        → Ramp
MediaSource(…) → MediaSource
\`\`\`

## Host prelude

\`\`\`text
component C <PointerInput>     // inbound pointer / focus / lifecycle
component C <EditableText>     // editing session + host verbs
protocol Api: component {
  requires PointerInput        // API protocols may require hosts
}
\`\`\`
`;
    writeOrCheck(join(OUT_SYMBOLS, "relationships.md"), body);
  }

  // —— Canonical symbols index (docs/reference/symbols.md) ——
  // Nested symbols/README.md is a stub: linking to README.md inside a folder
  // often fails to navigate in GitHub / IDE markdown previews.
  {
    const frames = (model.frameKinds || [])
      .map(
        (f) =>
          `- ${linkSymbol(f.name, "frame", "index", f.ctor)} (\`${f.name}\`) — ${f.summary}`,
      )
      .join("\n");
    const enums = allEnums
      .map(
        (e) =>
          `- ${linkSymbol(e.name, "enum", "index")} — ${(e.cases || []).map((c) => `\`.${c}\``).join(", ")}`,
      )
      .join("\n");
    const types = [
      ...(model.tokenTypes || []).map(
        (t) =>
          `- ${linkSymbol(t.name, "type", "index")} (${t.category}) — ${t.summary}`,
      ),
      ...(model.paramScalars || []).map(
        (t) =>
          `- ${linkSymbol(t.name, "type", "index")} (param scalar) — ${t.summary}`,
      ),
    ].join("\n");
    const ctors = (model.constructors || [])
      .map(
        (c) =>
          `- ${linkSymbol(c.name, "ctor", "index")} (${c.kind}) — ${c.summary}`,
      )
      .join("\n");
    const protocols = (model.protocols || [])
      .map(
        (p) =>
          `- ${linkSymbol(p.name, "protocol", "index")} (${p.role}) — ${p.summary}`,
      )
      .join("\n");

    const body = `# Symbol reference

Index of built-in PDL symbols. **Generated** from \`shared/language-model.json\` and \`shared/frame-props.json\`.

Regenerate: \`npm run docs:gen\`

## Frame kinds

${frames}

## Enums

${enums}

## Types

${types}

## Constructors

${ctors}

## Protocols

${protocols}

## Relationships

- [Inheritance-style relationships](symbols/relationships.md) (constructs / shares / requires)

## Machine sources

| File | Role |
|------|------|
| [\`shared/language-model.json\`](../../shared/language-model.json) | Token types, supplemental enums, constructors, protocols, errors, relationships |
| [\`shared/frame-props.json\`](../../shared/frame-props.json) | Frame property tables + host enum cases (compiler SoT) |
`;
    writeOrCheck(OUT_SYMBOLS_INDEX, body);

    const stub = `# Symbol reference

The symbol index is **[../symbols.md](../symbols.md)** (not this folder README — many Markdown previews do not navigate nested \`README.md\` links reliably).

Per-symbol pages live in this directory: \`frames/\`, \`enums/\`, \`types/\`, \`constructors/\`, \`protocols/\`.
`;
    writeOrCheck(join(OUT_SYMBOLS, "README.md"), stub);
  }

  // —— Errors catalog ——
  {
    const errors = (model.errors || []).filter((e) => e.severity === "error");
    const warnings = (model.errors || []).filter((e) => e.severity === "warning");
    const retired = (model.errors || []).filter((e) => e.severity === "retired");
    const row = (e) => `| **${e.code}** | \`${e.name}\` | ${e.summary} |`;

    const body = `# Error catalog

Stable diagnostic codes for conforming parsers and validators. **Generated** from \`shared/language-model.json\`.

Normative prose and message requirements: [\`docs/full-spec.md\` §24](../../full-spec.md#24--error-catalog).

## Errors (\`PDL-E\`)

| Code | Name | Summary |
|------|------|---------|
${errors.map(row).join("\n")}

## Warnings (\`PDL-W\`)

| Code | Name | Summary |
|------|------|---------|
${warnings.map(row).join("\n")}

## Retired

| Code | Name | Summary |
|------|------|---------|
${retired.map(row).join("\n")}
`;
    writeOrCheck(OUT_ERRORS, body);
  }

  if (CHECK) {
    if (process.exitCode) {
      console.error("Run: npm run docs:gen");
      process.exit(process.exitCode);
    }
    console.log("docs:gen --check OK");
    return;
  }

  const written = collectWrittenFiles(OUT_SYMBOLS);
  written.push(OUT_SYMBOLS_INDEX, OUT_ERRORS);
  console.log(
    `Generated ${written.length} files (fingerprint ${hashFiles(written)})`,
  );
}

main();
